const BACKEND_URL = process.env.NEXT_PUBLIC_BACKEND_URL || 'http://localhost:8000'

export async function querySociologyAgent(question, webSearch = false) {
  if (!question || !question.trim()) {
    throw new Error('Question cannot be empty')
  }

  const endpoint = `${BACKEND_URL}/query`

  try {
    const response = await fetch(endpoint, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        question: question.trim(),
        web_search: Boolean(webSearch),
      }),
    })

    if (!response.ok) {
      let errorMessage = `Server error (${response.status})`
      try {
        const errJson = await response.json()
        if (errJson.detail) {
          errorMessage = typeof errJson.detail === 'string' ? errJson.detail : JSON.stringify(errJson.detail)
        }
      } catch {}
      throw new Error(errorMessage)
    }

    const data = await response.json()
    return {
      answer: data.answer || 'No answer generated by agent.',
      question: data.question || question,
    }
  } catch (err) {
    if (err.name === 'TypeError' && err.message.includes('fetch')) {
      throw new Error(
        `Unable to reach backend server at ${BACKEND_URL}. Please ensure 'uv run uvicorn sociology_agent.server:app' is running.`
      )
    }
    throw err
  }
}
